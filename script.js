async function loadRealDocuments() {
  try {
    const response = await fetch('./loaded-documents.json');
    if (!response.ok) throw new Error('Cannot load real CRM docs');
    const payload = await response.json();
    state.realDocuments = Array.isArray(payload.documents) ? payload.documents : [];
    renderProjectAutoSummary();
  } catch (error) {
    console.warn('Loaded files not available, using sample data:', error);
    state.realDocuments = [];
  }
}

