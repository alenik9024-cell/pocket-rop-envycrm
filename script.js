async function loadPocketDeals() {
  if (!isAuthorized() || !pocketDeals) return;
  const requestId = ++state.pocketRequestId;
  state.pocketLoading = true;
  state.pocketError = '';
  state.pocketAnalysisError = '';
  renderPocketDashboard();
  renderAiRopDashboard();

  const query = new URLSearchParams({ period: reportPeriodSelect?.value || '30d', project_id: state.selectedProjectId || 'default' });
  if (state.selectedEmployeeId) query.set('employee_id', state.selectedEmployeeId);
  try {
    const response = await fetch(`/api/pocket/deals?${query.toString()}`);
    const payload = await response.json();
    if (!response.ok) throw new Error(payload.error || `Ошибка сервера: ${response.status}`);
    if (requestId !== state.pocketRequestId) return;
    state.pocketDeals = Array.isArray(payload.items) ? payload.items : [];
    state.pocketEmployees = Array.isArray(payload.employees) ? payload.employees : [];
    renderReportFilters();
  } catch (error) {
    if (requestId !== state.pocketRequestId) return;
    state.pocketDeals = [];
    state.pocketError = window.location.protocol === 'file:'
      ? 'Платформа открыта как локальный файл; CRM API доступен только через локальный сервер.'
      : error instanceof Error ? error.message : 'Неизвестная ошибка при загрузке CRM.';
  } finally {
    if (requestId === state.pocketRequestId) {
      state.pocketLoading = false;
      renderPocketDashboard();
  renderAiRopDashboard();
    }
  }
}

async function analyzeDeal(dealId) {
  if (state.pocketAnalyzingIds.has(dealId)) return;
  state.pocketAnalyzingIds.add(dealId);
  delete state.pocketDealErrors[dealId];
  state.pocketAnalysisError = '';
  renderPocketDashboard();
  renderAiRopDashboard();

  const controller = new AbortController();
    const timeoutId = window.setTimeout(() => controller.abort(), 900000);
  try {
    const query = new URLSearchParams({ project_id: state.selectedProjectId || 'default' });
    const selectedDeal = state.pocketDeals.find((item) => String(item.id) === String(dealId));
    const response = await fetch(`/api/pocket/deals/${encodeURIComponent(dealId)}/analyze?${query.toString()}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ deal: selectedDeal || { id: dealId } }),
      signal: controller.signal,
    });
    const payload = await response.json();
    if (!response.ok) throw new Error(payload.error || `Ошибка анализа: ${response.status}`);
    const deal = state.pocketDeals.find((item) => String(item.id) === String(dealId));
    if (deal) deal.review = payload.review;
  } catch (error) {
    state.pocketAnalysisError = error?.name === 'AbortError'
      ? 'Проверка превысила 15 минут. Первый запуск Whisper загружает модель; проверьте журнал сервера и повторите анализ.'
      : error instanceof Error ? error.message : 'Не удалось выполнить AI-анализ.';
    state.pocketDealErrors[dealId] = state.pocketAnalysisError;
  } finally {
    window.clearTimeout(timeoutId);
    state.pocketAnalyzingIds.delete(dealId);
    renderPocketDashboard();
  renderAiRopDashboard();
  }
}

async function sendCrmNote(dealId) {
  const deal = state.pocketDeals.find((item) => String(item.id) === String(dealId));
  if (!deal?.review) return;
  const button = document.querySelector(`[data-crm-note-deal="${CSS.escape(String(dealId))}"]`);
  if (button) { button.disabled = true; button.textContent = 'Отправляю…'; }
  try {
    const review = deal.review;
    const text = `AI-аудит сделки №${deal.id}\nСтатус: ${review.status_badge || review.outcome}\nКонтрольные точки: ${Object.entries(review.control_points || {}).map(([key, value]) => `${key}: ${value}`).join('; ')}\nШаги на закрытие: ${(review.closing_steps || []).map((item) => typeof item === 'string' ? item : `${item.step}. ${item.title}: ${item.target_action}`).join(' | ')}\nИнструкция РОПу: ${review.rop_feedback || review.recommendation}`;
    const response = await fetch(`/api/pocket/deals/${encodeURIComponent(dealId)}/note?project_id=${encodeURIComponent(state.selectedProjectId || 'default')}`, { method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({text}) });
    const payload = await response.json();
    if (!response.ok) throw new Error(payload.error || 'CRM не приняла замечание.');
    if (button) button.textContent = 'Замечание отправлено';
  } catch (error) {
    state.pocketAnalysisError = error instanceof Error ? error.message : 'Не удалось отправить замечание.';
    if (button) { button.disabled = false; button.textContent = 'Отправить замечание в CRM'; }
    renderPocketDashboard();
  renderAiRopDashboard();
  }
}

async function analyzeAllDeals() {
  const pending = state.pocketDeals.filter((deal) => !deal.review);
  if (!pending.length) return;
  if (analyzeAllDealsBtn) analyzeAllDealsBtn.disabled = true;
  state.pocketBatchAnalysis = { running: true, completed: 0, total: pending.length, errors: 0, current: '' };
  if (analyzeAllDealsBtn) analyzeAllDealsBtn.textContent = `Проверка 0 из ${pending.length}`;
  renderBatchAnalysisStatus();
  renderPocketDashboard();
  renderAiRopDashboard();
  try {
    for (const deal of pending) {
      state.pocketBatchAnalysis.current = deal.name || `№${deal.id}`;
      renderBatchAnalysisStatus();
      renderPocketDashboard();
  renderAiRopDashboard();
      await analyzeDeal(deal.id);
      if (state.pocketAnalysisError) state.pocketBatchAnalysis.errors += 1;
      state.pocketBatchAnalysis.completed += 1;
      if (analyzeAllDealsBtn) analyzeAllDealsBtn.textContent = `Проверка ${state.pocketBatchAnalysis.completed} из ${pending.length}`;
      renderBatchAnalysisStatus();
      renderPocketDashboard();
  renderAiRopDashboard();
    }
  } finally {
    if (state.pocketBatchAnalysis) {
      state.pocketBatchAnalysis.running = false;
      state.pocketBatchAnalysis.current = '';
      renderBatchAnalysisStatus();
      renderPocketDashboard();
  renderAiRopDashboard();
    }
    if (analyzeAllDealsBtn) analyzeAllDealsBtn.disabled = false;
    if (analyzeAllDealsBtn) analyzeAllDealsBtn.textContent = 'Проверить все';
  }
}

