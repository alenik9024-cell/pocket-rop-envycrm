function getProjectMetricSummary(project) {
  const tasks = (project.stages || []).flatMap((stage) => stage.tasks || []);
  const closed = tasks.filter((task) => task.status === 'Согласовано').length;
  const overdue = tasks.filter((task) => {
    const date = parseDate(task.dueDate);
    return date && date < new Date() && task.status !== 'Согласовано';
  }).length;
  const dueToday = tasks.filter((task) => {
    const date = parseDate(task.dueDate);
    if (!date || task.status === 'Согласовано') return false;
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    return date.getTime() === today.getTime();
  }).length;
  const approval = tasks.filter((task) => ['На согласовании', 'На проверке', 'На доработке'].includes(task.status)).length;
  return { total: tasks.length, closed, overdue, dueToday, approval };
}

function getRopMetricSummary(ropName) {
  const projects = sampleProjects.filter((project) => project.rop === ropName);
  const totals = projects.reduce((acc, project) => {
    const summary = getProjectMetricSummary(project);
    acc.total += summary.total;
    acc.closed += summary.closed;
    acc.overdue += summary.overdue;
    acc.dueToday += summary.dueToday;
    acc.approval += summary.approval;
    return acc;
  }, { total: 0, closed: 0, overdue: 0, dueToday: 0, approval: 0 });

  return {
    projectCount: projects.length,
    progress: Math.round(projects.reduce((sum, project) => sum + project.progress, 0) / (projects.length || 1)),
    ...totals,
  };
}

