function parseDate(value) {
  if (!value) return null;
  const normalized = value.split('.').reverse().join('-');
  const date = new Date(normalized);
  return Number.isNaN(date.getTime()) ? null : date;
}

function getProjectMetrics(project) {
  const tasks = (project.stages || []).flatMap((stage) => stage.tasks || []);
  const done = tasks.filter((task) => task.status === 'Согласовано').length;
  const approval = tasks.filter((task) => ['На согласовании', 'На проверке', 'На доработке'].includes(task.status)).length;
  const overdueTasks = tasks.filter((task) => {
    const date = parseDate(task.dueDate);
    return date && date < new Date() && task.status !== 'Согласовано';
  });
  const overdueDays = overdueTasks.reduce((sum, task) => {
    const date = parseDate(task.dueDate);
    if (!date) return sum;
    const diffDays = Math.max(0, Math.ceil((new Date() - date) / 86400000));
    return sum + diffDays;
  }, 0);

  return {
    total: tasks.length,
    done,
    approval,
    overdue: overdueTasks.length,
    overdueDays,
  };
}

