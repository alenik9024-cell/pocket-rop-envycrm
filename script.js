function formatDate(dateString) {
  const date = new Date(dateString);
  if (Number.isNaN(date.getTime())) return '';
  return `${String(date.getDate()).padStart(2, '0')}.${String(date.getMonth() + 1).padStart(2, '0')}.${date.getFullYear()}`;
}

function addDays(dateString, days) {
  const date = new Date(dateString);
  date.setDate(date.getDate() + Number(days));
  return date;
}

function buildContractNumber(dateString) {
  const date = new Date(dateString);
  const day = String(date.getDate()).padStart(2, '0');
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const year = String(date.getFullYear()).slice(-2);
  return `Договор № ${day}-${month}-${year}`;
}

function buildTechnicalMap(startDate, days) {
  const monthLabels = ['Месяц 1', 'Месяц 2', 'Месяц 3', 'Месяц 4'];
  const totalWeeks = Math.max(4, Math.ceil(days / 30));
  return monthLabels.slice(0, Math.min(totalWeeks, monthLabels.length)).map((label, index) => ({
    label,
    stage: index === 0 ? 'Диагностика и первичная ТК' : index === 1 ? 'Регламенты и скрипты' : index === 2 ? 'Запуск и согласование' : 'Финализация и контроль',
    due: formatDate(addDays(startDate, (index + 1) * 30).toISOString()),
  }));
}

