let lastAutomaticPocketAudit = localStorage.getItem('lastAutomaticPocketAudit') || '';
function scheduleDailyPocketAudit() {
  if (!isAuthorized()) return;
  const now = new Date();
  const dayKey = `${now.getFullYear()}-${now.getMonth() + 1}-${now.getDate()}`;
  // The browser's local timezone is the explicit schedule timezone. Running
  // once any time after 18:00 also covers a tab opened after the exact minute.
  if (now.getHours() >= 18 && lastAutomaticPocketAudit !== dayKey) {
    lastAutomaticPocketAudit = dayKey;
    localStorage.setItem('lastAutomaticPocketAudit', dayKey);
    loadPocketDeals().then(() => analyzeAllDeals());
  }
}
